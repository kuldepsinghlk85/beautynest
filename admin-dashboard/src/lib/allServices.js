// Helper Query Functions
export function getServiceById(serviceId) {
  return BEAUTYNEST_SERVICES.find(s => s.serviceId === serviceId || s.id === serviceId);
}

export function getServicesByCategory(category) {
  if (!category || category === 'All') return BEAUTYNEST_SERVICES;
  return BEAUTYNEST_SERVICES.filter(s => s.category.toLowerCase() === category.toLowerCase());
}

export function getServicesByGender(gender) {
  if (!gender || gender === 'All') return BEAUTYNEST_SERVICES;
  return BEAUTYNEST_SERVICES.filter(s => s.gender.toLowerCase().includes(gender.toLowerCase()));
}

export function searchServices(query) {
  if (!query) return BEAUTYNEST_SERVICES;
  const q = query.toLowerCase();
  return BEAUTYNEST_SERVICES.filter(s => 
    s.name.toLowerCase().includes(q) ||
    s.category.toLowerCase().includes(q) ||
    s.subCategory.toLowerCase().includes(q) ||
    s.keyFeatures.toLowerCase().includes(q) ||
    s.serviceId.toLowerCase().includes(q)
  );
}

